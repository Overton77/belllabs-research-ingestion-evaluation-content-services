#!/usr/bin/env python3
"""Run the docs retrieval experiment with headless Claude Code.

See README.md. Each (config, task) pair runs `claude -p` in a sandbox copy of the
documentation corpus and is scored on whether the expected files were retrieved and
the expected terms appear in the answer.

Usage:
  python experiments/docs_retrieval/run.py --config all --run-id 2026-10-07a
  python experiments/docs_retrieval/run.py --config index --task erc-term
  python experiments/docs_retrieval/run.py --config all --judge --model claude-sonnet-5-5
  python experiments/docs_retrieval/run.py --dry-run          # build sandboxes, run nothing
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
PACK_ROOT = REPO_ROOT.parent / "mission-control-general"
SCRATCH = REPO_ROOT / ".scratch" / "docs-retrieval"
RESULTS = HERE / "results"
INDEX_BEGIN = "<!-- BEGIN:mc-docs-index -->"
INDEX_END = "<!-- END:mc-docs-index -->"

CONFIGS: dict[str, dict[str, bool]] = {
    "baseline": {"index": False, "skill": False},
    "skill": {"index": False, "skill": True},
    "index": {"index": True, "skill": False},
    "both": {"index": True, "skill": True},
}

SEARCH_TOOL_PATTERN = "Bash(python docs/tools/okf_search.py:*)"
ALLOWED_TOOLS = ["Read", "Grep", "Glob", SEARCH_TOOL_PATTERN]
TASK_SUFFIX = (
    "\n\nAnswer concisely for an engineer on this project. Cite the repo-relative path(s) "
    "of the file(s) you relied on. If the docs do not answer, say so instead of guessing."
)


def load_tasks(only: list[str] | None) -> list[dict]:
    tasks = [json.loads(line) for line in (HERE / "tasks.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    if only:
        tasks = [t for t in tasks if t["id"] in only]
    return tasks


def strip_index(agents_text: str) -> str:
    if INDEX_BEGIN in agents_text and INDEX_END in agents_text:
        start = agents_text.index(INDEX_BEGIN)
        stop = agents_text.index(INDEX_END) + len(INDEX_END)
        text = agents_text[:start] + agents_text[stop:]
        return re.sub(r"\n## Documentation index\n\nGenerated by[^\n]*\n\n\n?", "\n", text)
    return agents_text


def copy_tree(src: Path, dst: Path, patterns: tuple[str, ...] = ("*.md", "*.py", "*.json")) -> None:
    for path in src.rglob("*"):
        if path.is_dir() or "__pycache__" in path.parts:
            continue
        if not any(path.match(p) for p in patterns):
            continue
        target = dst / path.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)


def build_sandbox(run_dir: Path, config: str) -> Path:
    flags = CONFIGS[config]
    root = run_dir / config
    repo = root / "mission-control"
    if repo.exists():
        shutil.rmtree(root)
    repo.mkdir(parents=True)
    shutil.copy2(REPO_ROOT / "GLOSSARY.md", repo / "GLOSSARY.md")
    copy_tree(REPO_ROOT / "docs", repo / "docs")
    for sub in ("general-mission-control", "workflow-types", "runtime-facts"):
        if (PACK_ROOT / sub).exists():
            copy_tree(PACK_ROOT / sub, root / "mission-control-general" / sub)
    agents = (REPO_ROOT / "AGENTS.md").read_text(encoding="utf-8").replace("\r\n", "\n")
    if not flags["index"]:
        agents = strip_index(agents)
    (repo / "AGENTS.md").write_text(agents, encoding="utf-8", newline="\n")
    (repo / "CLAUDE.md").write_text(agents, encoding="utf-8", newline="\n")
    if flags["skill"]:
        skill_src = REPO_ROOT / ".agents" / "skills" / "mission-control-docs" / "SKILL.md"
        skill_dst = repo / ".claude" / "skills" / "mission-control-docs" / "SKILL.md"
        skill_dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(skill_src, skill_dst)
    (repo / ".mcp-empty.json").write_text('{"mcpServers": {}}\n', encoding="utf-8")
    return repo


def claude_binary() -> str:
    found = shutil.which("claude")
    if not found:
        raise SystemExit("claude CLI not found on PATH")
    return found


def claude_command(model: str | None, max_turns: int) -> list[str]:
    # The prompt is passed on stdin to avoid shell quoting of multi-line text.
    cmd = [
        claude_binary(), "-p",
        "--output-format", "stream-json", "--verbose",
        "--max-turns", str(max_turns),
        "--no-session-persistence",
        "--strict-mcp-config", "--mcp-config", ".mcp-empty.json",
        "--allowedTools", *ALLOWED_TOOLS,
    ]
    if model:
        cmd += ["--model", model]
    return cmd


def run_claude(cmd: list[str], prompt: str, cwd: Path, timeout: int) -> tuple[list[dict], str]:
    env = dict(os.environ)
    env.setdefault("CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC", "1")
    proc = subprocess.run(cmd, cwd=cwd, input=prompt, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=timeout, env=env)
    events: list[dict] = []
    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return events, proc.stderr


def extract(events: list[dict]) -> dict:
    reads: list[str] = []
    searches: list[str] = []
    tool_names: list[str] = []
    result_text = ""
    cost = None
    turns = None
    usage = None
    duration = None
    for ev in events:
        if ev.get("type") == "assistant":
            for block in ev.get("message", {}).get("content", []):
                if block.get("type") == "tool_use":
                    name = block.get("name", "")
                    tool_names.append(name)
                    inp = block.get("input", {})
                    if name == "Read" and inp.get("file_path"):
                        reads.append(str(inp["file_path"]).replace("\\", "/"))
                    elif name == "Bash" and "okf_search" in str(inp.get("command", "")):
                        searches.append(str(inp["command"]))
                    elif name in ("Grep", "Glob"):
                        reads.append(f"{name}:{inp.get('pattern', '')}@{inp.get('path', '')}")
        elif ev.get("type") == "user":
            for block in ev.get("message", {}).get("content", []) or []:
                if block.get("type") == "tool_result":
                    content = block.get("content")
                    text = content if isinstance(content, str) else json.dumps(content)
                    for m in re.finditer(r"\(([^)]+\.md(?:#[^)]*)?)\)", text):
                        if "score=" in text:
                            searches.append("hit:" + m.group(1))
        elif ev.get("type") == "result":
            result_text = ev.get("result", "") or ""
            cost = ev.get("total_cost_usd")
            turns = ev.get("num_turns")
            usage = ev.get("usage")
            duration = ev.get("duration_ms")
    return {
        "reads": reads, "searches": searches, "tools": tool_names, "result": result_text,
        "cost_usd": cost, "turns": turns, "usage": usage, "duration_ms": duration,
    }


def score(task: dict, run: dict) -> dict:
    expected_files = [f.replace("\\", "/") for f in task["expected_files"]]
    seen = [r for r in run["reads"]] + [s.split("hit:", 1)[1] for s in run["searches"] if s.startswith("hit:")]
    retrieved = any(any(exp.rstrip("/") in s or s.endswith(exp) for s in seen) for exp in expected_files)
    answer = run["result"].lower()
    hits = [t for t in task["expected_terms"] if t.lower() in answer]
    answered = (len(hits) == len(task["expected_terms"])) if task.get("terms_mode", "all") == "all" else bool(hits)
    return {"retrieved": retrieved, "answered": answered, "pass": retrieved and answered, "term_hits": hits,
            "used_search": any(not s.startswith("hit:") for s in run["searches"])}


def judge(task: dict, answer: str, model: str | None, cwd: Path) -> dict:
    prompt = (
        "You are grading an answer about a software project whose documentation deliberately distinguishes "
        "what the specification requires from what the code implements today. Question:\n" + task["prompt"] +
        "\n\nExpected facts (each must be present and not contradicted): " + "; ".join(task["expected_terms"]) +
        "\n\nGrading rules: mark correct=true when every expected fact is stated and nothing in the answer contradicts it. "
        "An answer that reports the specified behaviour AND separately reports a narrower or different implemented "
        "behaviour is correct, not hedging, as long as it labels which is which. Mark correct=false only when an "
        "expected fact is missing, is asserted to be wrong, or the answer invents a fact that the docs do not support. "
        "Unverified-source caveats are not errors."
        "\n\nAnswer:\n" + answer +
        "\n\nReply with JSON only: {\"correct\": true|false, \"reason\": \"<one sentence>\"}"
    )
    cmd = [claude_binary(), "-p", "--output-format", "json", "--max-turns", "1", "--no-session-persistence",
           "--strict-mcp-config", "--mcp-config", ".mcp-empty.json", "--disallowedTools", "Read", "Grep", "Glob", "Bash", "Edit", "Write"]
    if model:
        cmd += ["--model", model]
    proc = subprocess.run(cmd, cwd=cwd, input=prompt, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=300)
    try:
        payload = json.loads(proc.stdout)
        text = payload.get("result", "")
        match = re.search(r"\{.*\}", text, re.S)
        verdict = json.loads(match.group(0)) if match else {"correct": None, "reason": "unparsed"}
        verdict["judge_cost_usd"] = payload.get("total_cost_usd")
        return verdict
    except (json.JSONDecodeError, AttributeError):
        return {"correct": None, "reason": "judge failed", "judge_cost_usd": None}


def summarize(rows: list[dict]) -> str:
    lines = ["| config | n | pass | retrieved | answered | used search | judge correct | mean turns | mean cost USD |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for config in CONFIGS:
        sub = [r for r in rows if r["config"] == config]
        if not sub:
            continue
        def rate(key: str) -> str:
            vals = [r[key] for r in sub if r.get(key) is not None]
            return f"{100 * sum(1 for v in vals if v) / len(vals):.0f}%" if vals else "-"
        turns = [r["turns"] for r in sub if r.get("turns") is not None]
        costs = [r["cost_usd"] for r in sub if r.get("cost_usd") is not None]
        lines.append(
            f"| {config} | {len(sub)} | {rate('pass')} | {rate('retrieved')} | {rate('answered')} | {rate('used_search')} | "
            f"{rate('judge_correct')} | {statistics.mean(turns):.1f} | {statistics.mean(costs):.3f} |"
            if turns and costs else
            f"| {config} | {len(sub)} | {rate('pass')} | {rate('retrieved')} | {rate('answered')} | {rate('used_search')} | {rate('judge_correct')} | - | - |"
        )
    return "\n".join(lines)


def rejudge(run_id: str, model: str | None) -> int:
    """Re-score a finished run with the current judge rubric and current tasks.jsonl, without re-running agents."""
    out_dir = RESULTS / run_id
    source = out_dir / "results.jsonl"
    if not source.exists():
        raise SystemExit(f"no results at {source}")
    tasks = {t["id"]: t for t in load_tasks(None)}
    rows = [json.loads(line) for line in source.read_text(encoding="utf-8").splitlines() if line.strip()]
    cwd = SCRATCH / run_id
    cwd.mkdir(parents=True, exist_ok=True)
    (cwd / ".mcp-empty.json").write_text('{"mcpServers": {}}\n', encoding="utf-8")
    rescored: list[dict] = []
    for row in rows:
        task = tasks.get(row["task"])
        if not task:
            rescored.append(row)
            continue
        synthetic = {"reads": row.get("reads", []), "searches": row.get("searches", []), "result": row.get("answer", "")}
        row.update(score(task, synthetic))
        if row.get("answer"):
            verdict = judge(task, row["answer"], model, cwd)
            row["judge_correct"] = verdict.get("correct")
            row["judge_reason"] = verdict.get("reason")
            row["judge_cost_usd"] = verdict.get("judge_cost_usd")
        rescored.append(row)
        print(f"[{row['config']}] {row['task']:<24} judge={row['judge_correct']} retrieved={row['retrieved']}")
    (out_dir / "results-rejudged.jsonl").write_text("\n".join(json.dumps(r) for r in rescored) + "\n", encoding="utf-8")
    summary = f"# Docs retrieval run {run_id} (re-judged)\n\nJudge model: {model or 'default'}; scored with the current rubric and tasks.jsonl\n\n" + summarize(rescored) + "\n"
    (out_dir / "summary-rejudged.md").write_text(summary, encoding="utf-8")
    print("\n" + summarize(rescored))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", action="append", default=None, help="config name or 'all' (repeatable)")
    parser.add_argument("--task", action="append", default=None, help="task id (repeatable)")
    parser.add_argument("--model", default=None)
    parser.add_argument("--run-id", default=None)
    parser.add_argument("--max-turns", type=int, default=15)
    parser.add_argument("--timeout", type=int, default=600, help="seconds per task")
    parser.add_argument("--judge", action="store_true", help="add an LLM judge verdict per answer")
    parser.add_argument("--dry-run", action="store_true", help="build sandboxes only")
    parser.add_argument("--rejudge", metavar="RUN_ID", help="re-run only the judge over a finished run's saved answers")
    args = parser.parse_args()

    if args.rejudge:
        return rejudge(args.rejudge, args.model)

    configs = list(CONFIGS) if not args.config or "all" in args.config else args.config
    for c in configs:
        if c not in CONFIGS:
            parser.error(f"unknown config {c}; choose from {', '.join(CONFIGS)}")
    tasks = load_tasks(args.task)
    if not tasks:
        parser.error("no tasks selected")
    run_id = args.run_id or dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    run_dir = SCRATCH / run_id
    out_dir = RESULTS / run_id
    out_dir.mkdir(parents=True, exist_ok=True)

    rows: list[dict] = []
    for config in configs:
        repo = build_sandbox(run_dir, config)
        print(f"[{config}] sandbox {repo}")
        if args.dry_run:
            continue
        for task in tasks:
            started = time.time()
            cmd = claude_command(args.model, args.max_turns)
            try:
                events, stderr = run_claude(cmd, task["prompt"] + TASK_SUFFIX, repo, args.timeout)
            except subprocess.TimeoutExpired:
                events, stderr = [], "timeout"
            run = extract(events)
            (repo / f"{task['id']}.jsonl").write_text("\n".join(json.dumps(e) for e in events), encoding="utf-8")
            if stderr.strip():
                (repo / f"{task['id']}.stderr.txt").write_text(stderr, encoding="utf-8")
            row = {"run_id": run_id, "config": config, "task": task["id"], "category": task.get("category"),
                   "model": args.model, **score(task, run), "turns": run["turns"], "cost_usd": run["cost_usd"],
                   "duration_ms": run["duration_ms"], "reads": run["reads"], "searches": run["searches"],
                   "answer": run["result"], "judge_correct": None}
            if args.judge and run["result"]:
                verdict = judge(task, run["result"], args.model, repo)
                row["judge_correct"] = verdict.get("correct")
                row["judge_reason"] = verdict.get("reason")
                row["judge_cost_usd"] = verdict.get("judge_cost_usd")
            rows.append(row)
            with (out_dir / "results.jsonl").open("a", encoding="utf-8") as fh:
                fh.write(json.dumps(row) + "\n")
            status = "PASS" if row["pass"] else ("retrieved" if row["retrieved"] else "MISS")
            print(f"[{config}] {task['id']:<22} {status:<9} turns={row['turns']} cost={row['cost_usd']} ({time.time() - started:.0f}s)")

    if rows:
        summary = f"# Docs retrieval run {run_id}\n\nModel: {args.model or 'default'}; tasks: {len(tasks)}; max turns: {args.max_turns}\n\n" + summarize(rows) + "\n"
        (out_dir / "summary.md").write_text(summary, encoding="utf-8")
        print("\n" + summarize(rows))
        print(f"\nresults: {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
